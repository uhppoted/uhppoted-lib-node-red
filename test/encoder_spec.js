const { Buffer } = require('node:buffer')

const describe = require('mocha').describe
const it = require('mocha').it
const expect = require('chai').expect
const encoder = require('../nodes/encoder.js')
const opcodes = require('../nodes/opcodes.js')

describe('encoder', function () {
  it('should encode set-ip request', function () {
    const controller = 405419896
    const address = '192.168.1.100'
    const netmask = '255.255.255.0'
    const gateway = '192.168.1.1'

    // prettier-ignore
    const expected = Buffer.from([
      0x17, 0x96, 0x00, 0x00, 0x78, 0x37, 0x2a, 0x18, 0xc0, 0xa8, 0x01, 0x64, 0xff, 0xff, 0xff, 0x00,
      0xc0, 0xa8, 0x01, 0x01, 0x55, 0xaa, 0xaa, 0x55, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    ])

    const request = encoder.SetIP(controller, { address, netmask, gateway })

    expect(request).to.deep.equal(expected)
  })

  it('should encode set-listener request', function () {
    const controller = 405419896
    const address = '192.168.1.100'
    const port = 60001
    const interval = 15

    // prettier-ignore
    const expected = Buffer.from([
      0x17, 0x90, 0x00, 0x00, 0x78, 0x37, 0x2a, 0x18, 0xc0, 0xa8, 0x01, 0x64, 0x61, 0xea, 0x0f, 0x00,
      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    ])

    const request = encoder.SetListener(controller, { address, port, interval })

    expect(request).to.deep.equal(expected)
  })

  it('should encode put-card request, with PIN and first-card', function () {
    const controller = 405419896
    const card = {
      card: 10058400,
      from: '2026-01-01',
      to: '2026-12-31',
      doors: {
        1: true,
        2: false,
        3: 17,
        4: true,
      },
      PIN: 999999,
      firstcard: {
        1: true,
        2: true,
        3: false,
        4: true,
      },
    }

    // prettier-ignore
    const expected = Buffer.from([
        0x17, 0x50, 0x00, 0x00, 0x78, 0x37, 0x2a, 0x18,  0xa0, 0x7a, 0x99, 0x00, 0x20, 0x26, 0x01, 0x01,
        0x20, 0x26, 0x12, 0x31, 0x01, 0x00, 0x11, 0x01,  0x3f, 0x42, 0x0f, 0x0b, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
      ])

    const request = encoder.PutCard(controller, card)

    expect(request).to.deep.equal(expected)
  })

  it('should encode get-antipassback request', function () {
    const controller = 405419896

    // prettier-ignore
    const expected = Buffer.from([
      0x17, 0x86, 0x00, 0x00, 0x78, 0x37, 0x2a, 0x18, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    ])

    const request = encoder.GetAntiPassback(controller, {})

    expect(request).to.deep.equal(expected)
  })

  it('should encode set-antipassback (1,3):(2,4) request', function () {
    const controller = 405419896

    // prettier-ignore
    const expected = Buffer.from([
      0x17, 0x84, 0x00, 0x00, 0x78, 0x37, 0x2a, 0x18, 0x02, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    ])

    const request = encoder.SetAntiPassback(controller, { antipassback: 2 })

    expect(request).to.deep.equal(expected)
  })

  it('should encode set-firstcard request', function () {
    const controller = 405419896
    const door = 3
    const firstcard = {
      door,
      startTime: '08:30',
      endTime: '17:45',
      modes: {
        active: opcodes.NormallyOpen,
        inactive: opcodes.FirstCardOnly,
      },
      weekdays: {
        monday: true,
        tuesday: true,
        wednesday: false,
        thursday: true,
        friday: false,
        saturday: false,
        sunday: true,
      },
    }

    // prettier-ignore
    const expected = Buffer.from([
        0x17, 0xaa, 0x00, 0x00, 0x78, 0x37, 0x2a, 0x18, 0x03, 0x08, 0x30, 0x01, 0x17, 0x45, 0x03, 0x01,
        0x01, 0x00, 0x01, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    ])

    const request = encoder.SetFirstCard(controller, firstcard)

    expect(request).to.deep.equal(expected)
  })

  it('should not encode invalid set-firstcard request', function () {
    const controller = 405419896
    const door = 3
    const firstcard = {
      door,
      startTime: '08:30',
      endTime: '17:45',
      modes: {
        active: opcodes.FirstCardOnly,
        inactive: opcodes.FirstCardOnly,
      },
      weekdays: {
        monday: true,
        tuesday: true,
        wednesday: false,
        thursday: true,
        friday: false,
        saturday: false,
        sunday: true,
      },
    }

    expect(() => encoder.SetFirstCard(controller, firstcard)).to.throw('invalid first-card active mode (first-card only)')
  })
})
